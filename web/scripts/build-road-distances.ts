/**
 * Builds src/server/domain/road-distances.generated.ts: real driving distances between every
 * pair of cities in domain/geo.ts, taken from an OSRM `table` request.
 *
 * Run it whenever cities are added:   npx tsx scripts/build-road-distances.ts
 * Own OSRM instance (recommended for anything beyond this one-off):  OSRM_URL=http://localhost:5000
 *
 * The result is committed, so runtime never depends on OSRM being reachable and
 * `estimateRoadKm` stays synchronous (it is used in client components and tight scoring loops).
 * OSRM's public demo server is fine for one request per rebuild; do not use it for traffic.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CITIES } from "../src/server/domain/geo";

const BASE = (process.env.OSRM_URL ?? "https://router.project-osrm.org").replace(/\/$/, "");
const OUT = resolve(__dirname, "../src/server/domain/road-distances.generated.ts");

async function main() {
  const coords = CITIES.map((c) => `${c.lng},${c.lat}`).join(";");
  const res = await fetch(`${BASE}/table/v1/driving/${coords}?annotations=distance`, {
    headers: { "User-Agent": "karvon-road-distances/1.0 (one-off build script)" },
    signal: AbortSignal.timeout(120_000),
  });
  if (!res.ok) throw new Error(`OSRM answered ${res.status}`);
  const body = (await res.json()) as { code: string; distances?: (number | null)[][]; message?: string };
  if (body.code !== "Ok" || !body.distances) throw new Error(`OSRM: ${body.code} ${body.message ?? ""}`);

  const entries: string[] = [];
  const missing: string[] = [];
  for (let i = 0; i < CITIES.length; i++) {
    for (let j = i + 1; j < CITIES.length; j++) {
      const ab = body.distances[i][j];
      const ba = body.distances[j][i];
      const known = [ab, ba].filter((x): x is number => typeof x === "number" && x > 0);
      const [a, b] = [CITIES[i].id, CITIES[j].id].sort();
      if (!known.length) {
        missing.push(`${a}|${b}`);
        continue;
      }
      // One-way streets make the two directions differ by a few km; a load board needs one number.
      const km = Math.round(known.reduce((s, x) => s + x, 0) / known.length / 1000);
      entries.push(`  "${a}|${b}": ${km},`);
    }
  }
  entries.sort();

  const file = `// GENERATED by scripts/build-road-distances.ts from OSRM (${new Date().toISOString().slice(0, 10)}) — do not edit by hand.
// Driving distance in km between city pairs, keyed "idA|idB" with ids sorted alphabetically.
// Pairs OSRM could not route are absent; geo.ts falls back to its great-circle estimate for them.
export const ROAD_KM: Record<string, number> = {
${entries.join("\n")}
};
`;
  writeFileSync(OUT, file);
  console.log(`wrote ${entries.length} pairs to ${OUT}`);
  if (missing.length) console.warn(`no route for ${missing.length} pairs:`, missing.join(", "));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
